        internal fun number(n: Double, lang: Lang): String {
            val symbols = DecimalFormatSymbols(if (lang == Lang.Ru) Locale.forLanguageTag("ru-RU") else Locale.US)
            // Как Intl в мини-аппе: по-русски разряды — неразрывный пробел U+00A0 (JDK и Android дают разный), дробь — запятая.
            if (lang == Lang.Ru) {
                symbols.groupingSeparator = '\u00a0'
                symbols.decimalSeparator = ','
            }
            return DecimalFormat("#,##0.##", symbols).format(n)
        }

