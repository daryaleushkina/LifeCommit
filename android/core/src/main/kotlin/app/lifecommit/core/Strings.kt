    private fun format(day: String, pattern: String): String {
        val date = Days.date(day) ?: return day
        return DateTimeFormatter.ofPattern(pattern, locale).format(date)
    }

    /** «26 сентября» / «September 26». */
    fun dayMonth(day: String): String = format(day, if (lang == Lang.Ru) "d MMMM" else "MMMM d")

    /** «пт, 3 октября» / «Fri, October 3» — подпись стоит внутри строки, по-русски строчными. */
    fun weekdayDayMonth(day: String): String {
        val date = Days.date(day) ?: return day
        if (lang == Lang.En) return format(day, "EEE, MMMM d")
        return "${ruWeekdaysShort[date.dayOfWeek.value - 1]}, ${format(day, "d MMMM")}"
    }

    /** «октябрь» — название месяца для подписей («по плану за октябрь»). */
    fun monthName(month: String): String {
        val date = Days.date("$month-15") ?: return month
        return DateTimeFormatter.ofPattern("LLLL", locale).format(date)
    }

    /** «15 окт» / «Oct 15» — коротко. */
    fun dayMonthShort(day: String): String = format(day, if (lang == Lang.Ru) "d MMM" else "MMM d").replace(".", "")

    /** «Октябрь 2026» — над календарём месяца. */
    fun monthYear(month: String): String = monthName(month).replaceFirstChar { it.titlecase(locale) } + " " + month.take(4)

    /** «понедельник, 5 октября» / «Monday, October 5» — заголовок шторки отметки задним числом. */
